#!/usr/bin/env python3
"""Bundle public/ (index.html + images) into a single Cloudflare Pages _worker.js.

Why: this lets the site deploy to Cloudflare Pages with one API request using only
the account API token (no separate asset-upload step).

Usage:  python3 build-worker.py OUT_DIR
Writes OUT_DIR/_worker.js
"""
import base64, json, mimetypes, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "public")
out_dir = sys.argv[1] if len(sys.argv) > 1 else "dist-worker"
os.makedirs(out_dir, exist_ok=True)

files = {}
for dirpath, _, names in os.walk(ROOT):
    for name in sorted(names):
        full = os.path.join(dirpath, name)
        rel = "/" + os.path.relpath(full, ROOT).replace(os.sep, "/")
        ctype = mimetypes.guess_type(name)[0] or "application/octet-stream"
        data = open(full, "rb").read()
        if ctype.startswith("text/") or ctype in ("application/json", "image/svg+xml"):
            if ctype.startswith("text/"):
                ctype += "; charset=utf-8"
            files[rel] = {"t": ctype, "s": data.decode("utf-8")}
        else:
            files[rel] = {"t": ctype, "b": base64.b64encode(data).decode("ascii")}

js = """// Generated by build-worker.py. Do not edit by hand.
const FILES = %s;
const cache = new Map();
function body(f) {
  if (f.s !== undefined) return f.s;
  let bytes = cache.get(f);
  if (!bytes) {
    const bin = atob(f.b);
    bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    cache.set(f, bytes);
  }
  return bytes;
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let path = decodeURIComponent(url.pathname);
    if (path === "/" || path === "") path = "/index.html";
    const f = FILES[path];
    if (!f) {
      return new Response("Not found", { status: 404, headers: { "content-type": "text/plain; charset=utf-8" } });
    }
    const isHtml = f.t.startsWith("text/html");
    return new Response(request.method === "HEAD" ? null : body(f), {
      headers: {
        "content-type": f.t,
        "cache-control": isHtml ? "no-cache" : "public, max-age=604800",
        "x-content-type-options": "nosniff"
      }
    });
  }
};
""" % json.dumps(files)

path = os.path.join(out_dir, "_worker.js")
open(path, "w").write(js)
print(path, len(js) // 1024, "KB,", len(files), "files:", ", ".join(sorted(files)))
